"""libSQL Hrana HTTP v2 adapter with stateful, atomic transactions.

Protocol: https://github.com/tursodatabase/libsql/blob/main/docs/HTTP_V2_SPEC.md
No SDK-specific assumptions escape this module. No retry of ambiguous writes.
"""

from __future__ import annotations

import base64
import logging
import sqlite3
import sys
from collections.abc import Mapping
from pathlib import Path
from urllib.parse import urlparse
from uuid import uuid4

import httpx
from amora.security import validate_remote_origin
from .backend import StorageCapabilities

logger = logging.getLogger(__name__)


class StorageUnavailable(sqlite3.OperationalError):
    pass


class Result:
    def __init__(self, columns=(), rows=(), rowcount=0):
        self._rows = [Row(columns, values) for values in rows]
        self.rowcount = rowcount
        self._index = 0

    def fetchone(self):
        if self._index >= len(self._rows):
            return None
        item = self._rows[self._index]
        self._index += 1
        return item

    def fetchall(self):
        rows = self._rows[self._index :]
        self._index = len(self._rows)
        return rows

    def __iter__(self):
        while (row := self.fetchone()) is not None:
            yield row


class Row(Mapping):
    def __init__(self, columns, values):
        self.columns, self.values = tuple(columns), tuple(values)

    def __getitem__(self, key):
        return self.values[key if isinstance(key, int) else self.columns.index(key)]

    def __iter__(self):
        return iter(self.columns)

    def __len__(self):
        return len(self.columns)


def _encode(value):
    if value is None:
        return {"type": "null"}
    if isinstance(value, bool):
        value = int(value)
    if isinstance(value, int):
        return {"type": "integer", "value": str(value)}
    if isinstance(value, float):
        return {"type": "float", "value": value}
    if isinstance(value, bytes):
        return {"type": "blob", "base64": base64.b64encode(value).decode()}
    if isinstance(value, str):
        return {"type": "text", "value": value}
    raise TypeError("unsupported SQL parameter type")


def _decode(value):
    kind = value["type"]
    if kind == "null":
        return None
    if kind == "integer":
        return int(value["value"])
    if kind == "float":
        return float(value["value"])
    if kind == "text":
        return value["value"]
    if kind == "blob":
        return base64.b64decode(value["base64"], validate=True)
    raise StorageUnavailable("INVALID_SQL_VALUE")


def statements(script):
    """SQLite's parser detects statement boundaries, including trigger bodies."""
    pending = ""
    for char in script:
        pending += char
        if char == ";" and sqlite3.complete_statement(pending):
            if pending.strip():
                yield pending
            pending = ""
    if pending.strip():
        if not sqlite3.complete_statement(pending + ";"):
            raise ValueError("incomplete SQL script")
        yield pending


class LibSQLBackend:
    capabilities = StorageCapabilities("libsql", False, True, remote=True)

    def __init__(self, url: str, token: str, *, transport=None, timeout=15.0):
        if url.startswith("libsql://"):
            url = "https://" + url[len("libsql://") :]
        url = validate_remote_origin(url)
        parsed = urlparse(url)
        if (
            parsed.scheme != "https"
            or not parsed.hostname
            or parsed.username
            or parsed.password
            or parsed.query
            or parsed.fragment
            or parsed.path not in {"", "/"}
        ):
            raise ValueError(
                "libSQL requires an HTTPS origin without credentials or path"
            )
        if not token:
            raise ValueError("libSQL auth token is required")
        self.url, self._token = url.rstrip("/"), token
        self.transport, self.timeout = transport, timeout

    def connect(self, path: Path):
        return RemoteConnection(self)

    def backup(self, connection, destination: Path):
        """Consistent logical export to a portable SQLite snapshot, including FTS.

        Shadow tables are regenerated by SQLite, never copied as ordinary tables.
        Unknown virtual modules fail explicitly. No credential or local cache export.
        """
        destination.parent.mkdir(parents=True, exist_ok=True)
        temporary = destination.with_suffix(destination.suffix + ".partial")
        temporary.unlink(missing_ok=True)
        target = sqlite3.connect(temporary)
        try:
            target.execute("PRAGMA foreign_keys=OFF")
            with connection:
                schema = connection.execute(
                    "SELECT type,name,tbl_name,sql FROM sqlite_schema WHERE sql IS NOT NULL ORDER BY rowid"
                ).fetchall()
                tables = [
                    r
                    for r in schema
                    if r["type"] == "table" and not r["name"].startswith("sqlite_")
                ]
                for row in tables:
                    name, sql = row["name"], row["sql"]
                    if name.startswith("memory_fts_"):
                        continue
                    if "VIRTUAL TABLE" in sql.upper() and name != "memory_fts":
                        raise ValueError("unsupported virtual table in snapshot")
                    target.execute(sql)
                    quoted = '"' + name.replace('"', '""') + '"'
                    rows = connection.execute("SELECT * FROM " + quoted).fetchall()
                    if rows:
                        target.executemany(
                            "INSERT INTO "
                            + quoted
                            + " VALUES ("
                            + ",".join("?" for _ in rows[0])
                            + ")",
                            [tuple(r.values) for r in rows],
                        )
                if any(row["name"] == "sqlite_sequence" for row in schema):
                    sequence = connection.execute(
                        "SELECT name,seq FROM sqlite_sequence"
                    ).fetchall()
                    target.execute("DELETE FROM sqlite_sequence")
                    target.executemany(
                        "INSERT INTO sqlite_sequence(name,seq) VALUES (?,?)",
                        [(r[0], r[1]) for r in sequence],
                    )
                for row in schema:
                    if row["type"] in {"index", "trigger", "view"} and not row[
                        "tbl_name"
                    ].startswith("memory_fts_"):
                        target.execute(row["sql"])
            target.commit()
            if (
                target.execute("PRAGMA integrity_check").fetchone()[0] != "ok"
                or target.execute("PRAGMA foreign_key_check").fetchone() is not None
            ):
                raise ValueError("snapshot integrity failed")
            target.close()
            temporary.replace(destination)
            return destination
        except BaseException:
            target.close()
            temporary.unlink(missing_ok=True)
            raise


class RemoteConnection:
    def __init__(self, backend):
        self.backend = backend
        self.client = self._new_client()
        self._baton = None
        self._transaction = False
        self._transaction_started = False
        self._closed = False
        self._broken = False
        self._previous_error = None
        self._recovering_from = None
        self._connection_id = str(uuid4())
        self._generation = 0

    def _new_client(self):
        return httpx.Client(
            timeout=self.backend.timeout,
            transport=self.backend.transport,
            follow_redirects=False,
        )

    def _log_fields(self):
        return {
            "backend": "libsql",
            "connection_id": self._connection_id,
            "generation": self._generation,
        }

    def _poison(self, code, *, exception_type=None):
        self._broken = True
        self._baton = None
        self._previous_error = code
        logger.warning(
            "storage_connection_poisoned",
            extra={
                **self._log_fields(),
                "error_code": code,
                "exception_type": exception_type,
            },
        )

    def _ensure_ready(self):
        if self._closed or (self._broken and self._transaction):
            raise StorageUnavailable("SQL_CONNECTION_CLOSED")
        if not self._broken:
            return
        # This is entry to a *new* operation, after the failed context unwound.
        # Never retain/replay the failed SQL, arguments, baton or HTTP pool.
        self._baton = None
        try:
            self.client.close()
        except Exception:
            logger.warning(
                "storage_client_disposal_failed",
                extra={**self._log_fields(), "error_code": "SQL_CLIENT_CLOSE_FAILED"},
            )
        try:
            client = self._new_client()
        except Exception as exc:
            raise StorageUnavailable("SQL_CONNECTION_RECOVERY_FAILED") from exc
        self.client = client
        self._recovering_from = self._previous_error
        self._generation += 1
        self._broken = False

    def _pipeline(self, requests):
        self._ensure_ready()
        try:
            initialize = self._baton is None and requests[0]["type"] != "close"
            if initialize:
                requests = [
                    {
                        "type": "execute",
                        "stmt": {
                            "sql": "PRAGMA foreign_keys=ON",
                            "args": [],
                            "want_rows": False,
                        },
                    }
                ] + requests
            response = self.client.post(
                self.backend.url + "/v2/pipeline",
                headers={"Authorization": "Bearer " + self.backend._token},
                json={"baton": self._baton, "requests": requests},
            )
            response.raise_for_status()
            data = response.json()
            self._baton = data["baton"]
            # base_url may change routing, but never forward credentials to a new origin.
            base = data.get("base_url")
            if base and base.rstrip("/") != self.backend.url:
                raise StorageUnavailable("SQL_ROUTING_ORIGIN_CHANGED")
            results = data["results"]
            if len(results) != len(requests):
                raise StorageUnavailable("SQL_INVALID_RESPONSE")
        except Exception as exc:
            self._poison(
                "SQL_TRANSPORT_FAILED_OUTCOME_UNKNOWN",
                exception_type=type(exc).__name__,
            )
            raise StorageUnavailable("SQL_TRANSPORT_FAILED_OUTCOME_UNKNOWN") from exc
        if initialize:
            if results[0]["type"] != "ok":
                self._poison("SQL_FOREIGN_KEYS_UNAVAILABLE")
                raise StorageUnavailable("SQL_FOREIGN_KEYS_UNAVAILABLE")
            results = results[1:]
        return results

    @staticmethod
    def _request(sql, parameters=(), *, want_rows=True):
        return {
            "type": "execute",
            "stmt": {
                "sql": sql,
                "args": [_encode(v) for v in parameters],
                "want_rows": want_rows,
            },
        }

    @staticmethod
    def _decode_execute(first, sql):
        if first["type"] == "error":
            code = first["error"].get("code", "SQL_ERROR")
            # Messages may contain SQL values; expose only machine codes.
            error = (
                sqlite3.IntegrityError
                if code in {"SQLITE_CONSTRAINT_UNIQUE", "SQLITE_CONSTRAINT_PRIMARYKEY"}
                else sqlite3.DatabaseError
            )
            if code.startswith("SQLITE_CONSTRAINT"):
                failure = error(code)
                failure.sqlite_errorname = code
                failure.sqlite_errorcode = getattr(
                    sqlite3, code, sqlite3.SQLITE_CONSTRAINT
                )
                raise failure
            if code == "SQLITE_ERROR":
                message = first["error"].get("message", "")
                if "no such module: fts5" in message:
                    raise sqlite3.OperationalError("FTS5_UNSUPPORTED")
            raise StorageUnavailable(code)
        if first["type"] != "ok" or first["response"]["type"] != "execute":
            raise StorageUnavailable("SQL_INVALID_RESPONSE")
        payload = first["response"]["result"]
        rowcount = payload.get("affected_row_count")
        if type(rowcount) is not int or rowcount < 0:
            raise StorageUnavailable("SQL_INVALID_RESPONSE")
        return Result(
            [c["name"] for c in payload["cols"]],
            [[_decode(v) for v in row] for row in payload["rows"]],
            rowcount,
        )

    def execute(self, sql, parameters=()):
        if isinstance(parameters, dict):
            raise TypeError("named parameters are not used by Amora stores")
        normalized = sql.strip().rstrip(";").strip().upper()
        starting_transaction = self._transaction and not self._transaction_started
        requests = []
        if starting_transaction:
            # BEGIN and the first real statement share one network round-trip.
            requests.append(self._request("BEGIN IMMEDIATE", (), want_rows=False))
        requests.append(self._request(sql, parameters))
        if not self._transaction:
            requests.append({"type": "close"})
        results = self._pipeline(requests)
        try:
            offset = 0
            if starting_transaction:
                self._decode_execute(results[0], "BEGIN IMMEDIATE")
                self._transaction_started = True
                offset = 1
            result = self._decode_execute(results[offset], sql)
        except BaseException:
            if self._transaction and self._baton is None:
                self._poison("SQL_TRANSACTION_STREAM_LOST")
            raise
        # A successful terminator no longer needs a stateful stream. Validate
        # only after processing its SQL result, so errors never become success.
        if (
            self._transaction
            and self._transaction_started
            and self._baton is None
            and normalized not in {"COMMIT", "ROLLBACK"}
        ):
            self._poison("SQL_TRANSPORT_FAILED_OUTCOME_UNKNOWN")
            raise StorageUnavailable(
                "SQL_TRANSPORT_FAILED_OUTCOME_UNKNOWN"
            ) from StorageUnavailable("SQL_TRANSACTION_STREAM_LOST")
        if self._recovering_from is not None:
            # Client construction is not recovery: bootstrap, SQL result and
            # transaction continuity must all have passed validation.
            logger.info(
                "storage_connection_recovered",
                extra={**self._log_fields(), "previous_error": self._recovering_from},
            )
            self._recovering_from = None
        return result

    def executemany(self, sql, values):
        items = list(values)
        if not items:
            return Result(rowcount=0)
        if not self._transaction:
            # Preserve the historical DB-API behavior outside an explicit atomic
            # context: each statement commits independently and a later failure
            # does not roll back prior successful rows.
            total = 0
            for value in items:
                total += self.execute(sql, value).rowcount
            return Result(rowcount=total)

        starting_transaction = not self._transaction_started
        requests = []
        if starting_transaction:
            requests.append(self._request("BEGIN IMMEDIATE", (), want_rows=False))
        requests.extend(self._request(sql, value) for value in items)
        results = self._pipeline(requests)
        try:
            offset = 0
            if starting_transaction:
                self._decode_execute(results[0], "BEGIN IMMEDIATE")
                self._transaction_started = True
                offset = 1
            total = 0
            for item in results[offset:]:
                total += self._decode_execute(item, sql).rowcount
        except BaseException:
            if self._baton is None:
                self._poison("SQL_TRANSACTION_STREAM_LOST")
            raise
        if self._baton is None:
            self._poison("SQL_TRANSPORT_FAILED_OUTCOME_UNKNOWN")
            raise StorageUnavailable(
                "SQL_TRANSPORT_FAILED_OUTCOME_UNKNOWN"
            ) from StorageUnavailable("SQL_TRANSACTION_STREAM_LOST")
        return Result(rowcount=total)

    def executescript(self, script):
        # Migrations supply explicit BEGIN/COMMIT and rollback on failure.
        owns_transaction = False
        try:
            for sql in statements(script):
                normalized = sql.strip().rstrip(";").upper()
                if normalized.startswith("BEGIN"):
                    self.__enter__()
                    owns_transaction = True
                elif normalized == "COMMIT":
                    self.__exit__(None, None, None)
                    owns_transaction = False
                elif normalized == "ROLLBACK":
                    self.__exit__(RuntimeError, None, None)
                    owns_transaction = False
                else:
                    self.execute(sql)
        except BaseException:
            if owns_transaction and self._transaction:
                self.__exit__(*sys.exc_info())
            raise

    def __enter__(self):
        if self._transaction:
            raise RuntimeError("nested transactions are not supported")
        self._ensure_ready()
        self._transaction = True
        self._transaction_started = False
        return self

    def __exit__(self, kind, value, traceback):
        try:
            if self._transaction and self._broken and kind is None:
                raise StorageUnavailable("SQL_CONNECTION_CLOSED")
            if (
                self._transaction
                and self._transaction_started
                and not self._broken
                and not self._closed
            ):
                try:
                    self.execute("COMMIT" if kind is None else "ROLLBACK")
                finally:
                    if self._baton is not None:
                        self._pipeline([{"type": "close"}])
        finally:
            self._transaction = False
            self._transaction_started = False
            self._baton = None

    def close(self):
        try:
            if not self._closed and not self._broken and self._baton is not None:
                self._pipeline([{"type": "close"}])
        finally:
            self._closed = True
            self.client.close()
